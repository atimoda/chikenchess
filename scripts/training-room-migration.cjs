#!/usr/bin/env node
// Writes supabase/migrations/<stamp>_training_room.sql: puts the Training room of lib/pigchicken/example-training.ts
// into the Training room row of the database (TRAINING_PATIO_ID of lib/pigchicken/example-menu.ts, an older row the
// example migrations keep with its own layout). Only the layout changes: name, creator, godparent and the rest stay;
// the revision goes up, so every browser takes the new layout instead of its copy. Without that row nothing happens.
// Usage: node scripts/training-room-migration.cjs AAAAMMDDNNNN
const fs = require('node:fs')
const path = require('node:path')
const { loadTs } = require('../tests/helpers/music.cjs')

const stamp = process.argv[2]
if (!/^\d{12}$/.test(stamp ?? '')) { console.error('Usage: node scripts/training-room-migration.cjs AAAAMMDDNNNN'); process.exit(1) }
const { trainingLayout } = loadTs('lib/pigchicken/example-training.ts')
const { TRAINING_PATIO_ID } = loadTs('lib/pigchicken/example-menu.ts')
const json = JSON.stringify(trainingLayout())
const tag = '$layout$'
if (json.length > 400000) throw new Error(`layout too large (${json.length})`)
if (json.includes(tag)) throw new Error('layout holds the quoting tag')
const sql = [
  '-- Generated by scripts/training-room-migration.cjs from lib/pigchicken/example-training.ts: the Training room\'s',
  `-- layout in its row of the database (${TRAINING_PATIO_ID}). Only the layout changes (name, creator, godparent and`,
  '-- featured stay); the revision goes up so every browser takes it instead of its own copy.',
  'update online_private.patio_lobbies',
  `  set layout = ${tag}${json}${tag}::jsonb, revision = revision + 1, updated_at = clock_timestamp(), last_edited_at = clock_timestamp()`,
  `  where id = '${TRAINING_PATIO_ID}'::uuid;`,
  '',
].join('\n')
const out = path.join(__dirname, '..', 'supabase', 'migrations', `${stamp}_training_room.sql`)
fs.writeFileSync(out, sql)
console.log(`wrote ${path.relative(process.cwd(), out)} (${Math.round(json.length / 1024)} KB)`)
