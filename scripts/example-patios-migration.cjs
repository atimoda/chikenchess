#!/usr/bin/env node
// Writes supabase/migrations/<stamp>_example_patios.sql: the example Pátios of lib/pigchicken/example-seed.ts as
// normal lobbies of the admin's account, featured. Usage: node scripts/example-patios-migration.cjs 202611120002
const fs = require('node:fs')
const path = require('node:path')
const { loadTs } = require('../tests/helpers/music.cjs')

const stamp = process.argv[2]
if (!/^\d{12}$/.test(stamp ?? '')) { console.error('Usage: node scripts/example-patios-migration.cjs AAAAMMDDNNNN'); process.exit(1) }
const { EXAMPLE_PATIOS, ADMIN_PROFILE_CODE } = loadTs('lib/pigchicken/example-seed.ts')
const q = s => `'${String(s).replace(/'/g, "''")}'`
const rows = EXAMPLE_PATIOS.map(e => {
  const json = JSON.stringify(e.layout())
  if (json.length > 400000) throw new Error(`${e.name}: layout too large (${json.length})`)
  if (json.includes('$layout$')) throw new Error(`${e.name}: layout holds the quoting tag`)
  return `  perform pg_temp.example_patio(${q(e.id)}::uuid, ${q(e.name)}, $layout$${json}$layout$::jsonb, admin_id);`
})
const sql = `-- Generated by scripts/example-patios-migration.cjs from lib/pigchicken/example-seed.ts: the example Pátios as
-- normal lobbies of the admin's account (profile code ${ADMIN_PROFILE_CODE}): creator, godparent and who saved it,
-- featured (Destaques). A row that already has the example's id or name keeps its layout (the admin may have edited
-- it): it is only given to the admin's account and featured. Without that account (a local database) nothing happens.
create or replace function pg_temp.example_patio(p_id uuid, p_name text, p_layout jsonb, p_admin uuid) returns void language plpgsql as $f$
declare found_id uuid;
begin
  select id into found_id from online_private.patio_lobbies where id = p_id or lower(name) = lower(p_name) order by (id = p_id) desc, updated_at desc limit 1;
  if found_id is null then
    insert into online_private.patio_lobbies (id, name, layout, creator_id, godparent_id, saved_by, featured)
      values (p_id, p_name, p_layout, p_admin, p_admin, p_admin, true);
    found_id := p_id;
  else
    update online_private.patio_lobbies set creator_id = p_admin, godparent_id = p_admin, saved_by = p_admin, featured = true, name = coalesce(name, p_name) where id = found_id;
  end if;
  insert into online_private.patio_lobby_people (lobby_id, user_id, edited_at) values (found_id, p_admin, clock_timestamp())
    on conflict (lobby_id, user_id) do update set edited_at = coalesce(online_private.patio_lobby_people.edited_at, excluded.edited_at);
end $f$;

do $$
declare admin_id uuid;
begin
  select id into admin_id from public.online_profiles where code = ${q(ADMIN_PROFILE_CODE)};
  if admin_id is null then return; end if;
${rows.join('\n')}
end $$;
`
const out = path.join(__dirname, '..', 'supabase', 'migrations', `${stamp}_example_patios.sql`)
fs.writeFileSync(out, sql)
console.log(`${path.relative(process.cwd(), out)}: ${EXAMPLE_PATIOS.length} example(s), ${sql.length} bytes`)
