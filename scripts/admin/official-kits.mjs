import crypto from 'node:crypto'
import fs from 'node:fs/promises'
import path from 'node:path'

const KITS_DIRECTORY = 'data/music/kits'
// Plain JavaScript on purpose: `official-kits.d.ts` types the map, so the type checker never has to read
// every kit's JSON (dozens of megabytes) just to learn that it is data.
const INDEX_FILE = 'lib/music/official-kits.js'

async function writeAtomic(target, text) {
  const temporary = `${target}.tmp-${process.pid}-${crypto.randomBytes(6).toString('hex')}`
  try { await fs.writeFile(temporary, text); await fs.rename(temporary, target) }
  catch (error) { await fs.rm(temporary, { force: true }).catch(() => {}); throw error }
}

/** Lists every saved city kit in the bundled index, in a stable order. */
export async function writeOfficialKitIndex(root) {
  const files = (await fs.readdir(path.join(root, KITS_DIRECTORY)).catch(() => []))
    .filter(file => /^[a-z0-9-]+\.json$/.test(file)).sort()
  const ids = files.map(file => file.slice(0, -5))
  const imports = ids.map((id, index) => `import kit${index} from '../../${KITS_DIRECTORY}/${id}.json'\n`).join('')
  const entries = ids.map((id, index) => `  '${id}': kit${index},\n`).join('')
  await writeAtomic(path.join(root, INDEX_FILE), `// Generated by the local Admin's "Save DB" in Creative (scripts/admin/official-kits.mjs).
// Each entry is a complete kit that replaces the city's profile-generated default.
${imports}export const OFFICIAL_CITY_KITS = {
${entries}}
`)
  return ids
}

/** Saves one validated kit as the city's official kit and refreshes the index. */
export async function saveOfficialKit(root, cityId, kit) {
  if (!/^[a-z0-9-]+$/.test(cityId)) throw new Error('invalid city')
  const directory = path.join(root, KITS_DIRECTORY)
  await fs.mkdir(directory, { recursive: true })
  await writeAtomic(path.join(directory, `${cityId}.json`), `${JSON.stringify(kit, null, 2)}\n`)
  await writeOfficialKitIndex(root)
  return { path: `${KITS_DIRECTORY}/${cityId}.json`, revision: kit.catalogRevision }
}
