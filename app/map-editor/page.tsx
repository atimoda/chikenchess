"use client"

import { useState, useRef, useEffect } from "react"
import { cities as initialCities, CityData } from "@/lib/cities-data"
import { cn } from "@/lib/utils"

export default function MapEditorPage() {
  const [cities, setCities] = useState<CityData[]>(initialCities)
  const [selectedCityId, setSelectedCityId] = useState<string | null>(null)
  const [isDragging, setIsDragging] = useState(false)
  const mapRef = useRef<HTMLDivElement>(null)

  const handleMouseDown = (e: React.MouseEvent, cityId: string) => {
    e.stopPropagation()
    setSelectedCityId(cityId)
    setIsDragging(true)
  }

  const handleMouseMove = (e: React.MouseEvent) => {
    if (!isDragging || !selectedCityId || !mapRef.current) return

    const rect = mapRef.current.getBoundingClientRect()
    const x = ((e.clientX - rect.left) / rect.width) * 100
    const y = ((e.clientY - rect.top) / rect.height) * 100

    setCities(prev => prev.map(c => {
      if (c.id === selectedCityId) {
        return {
          ...c,
          coordinates: { x, y }
        }
      }
      return c
    }))
  }

  const handleMouseUp = () => {
    setIsDragging(false)
  }

  const handleSave = () => {
    const coordinatesMap = cities.reduce((acc, c) => {
      acc[c.id] = {
        x: Math.round(c.coordinates.x * 100) / 100,
        y: Math.round(c.coordinates.y * 100) / 100
      }
      return acc
    }, {} as Record<string, { x: number, y: number }>)
    
    const output = `// This file is auto-generated by the Map Editor\n// Do not edit manually if you plan to use the visual editor.\n\nexport const cityCoordinates: Record<string, { x: number; y: number }> = ${JSON.stringify(coordinatesMap, null, 2)}`
    
    navigator.clipboard.writeText(output)
    alert("Coordinates file content copied to clipboard! Check console as well.")
    console.log(output)
  }

  // Handle keyboard nudge
  useEffect(() => {
    const handleKeyDown = (e: KeyboardEvent) => {
      if (!selectedCityId) return

      const step = e.shiftKey ? 1 : 0.1
      
      setCities(prev => prev.map(c => {
        if (c.id === selectedCityId) {
          let { x, y } = c.coordinates
          if (e.key === "ArrowLeft") x -= step
          if (e.key === "ArrowRight") x += step
          if (e.key === "ArrowUp") y -= step
          if (e.key === "ArrowDown") y += step
          return { ...c, coordinates: { x, y } }
        }
        return c
      }))
    }

    window.addEventListener("keydown", handleKeyDown)
    return () => window.removeEventListener("keydown", handleKeyDown)
  }, [selectedCityId])

  return (
    <div 
      className="flex flex-col h-screen bg-neutral-900 text-white"
      onMouseUp={handleMouseUp}
      onMouseLeave={handleMouseUp}
    >
      <header className="p-4 border-b border-neutral-800 flex justify-between items-center bg-neutral-950">
        <h1 className="text-xl font-bold">Map Coordinate Editor</h1>
        <div className="flex gap-4">
          <div className="text-sm text-neutral-400">
            Selected: {selectedCityId ? cities.find(c => c.id === selectedCityId)?.name : "None"}
            {selectedCityId && (
              <span className="ml-2 font-mono">
                X: {cities.find(c => c.id === selectedCityId)?.coordinates.x.toFixed(2)}% 
                Y: {cities.find(c => c.id === selectedCityId)?.coordinates.y.toFixed(2)}%
              </span>
            )}
          </div>
          <button 
            onClick={handleSave}
            className="px-4 py-2 bg-green-600 hover:bg-green-700 rounded font-bold text-sm"
          >
            Save Coordinates
          </button>
        </div>
      </header>

      <div className="flex-1 flex overflow-hidden">
        {/* Sidebar List */}
        <div className="w-64 border-r border-neutral-800 overflow-y-auto bg-neutral-950 p-2">
          {cities.map(city => (
            <div
              key={city.id}
              onClick={() => setSelectedCityId(city.id)}
              className={cn(
                "p-2 rounded cursor-pointer text-sm mb-1 flex items-center justify-between",
                selectedCityId === city.id ? "bg-blue-900 text-blue-100" : "hover:bg-neutral-800 text-neutral-300"
              )}
            >
              <span>{city.name}</span>
              <div 
                className="w-3 h-3 rounded-full" 
                style={{ backgroundColor: city.color }}
              />
            </div>
          ))}
        </div>

        {/* Map Area */}
        <div className="flex-1 relative bg-neutral-900 flex items-center justify-center p-8 overflow-hidden">
           <div 
             ref={mapRef}
             className="relative w-full"
             style={{ 
               aspectRatio: "201/97",
               maxWidth: "100%",
             }}
             onMouseMove={handleMouseMove}
           >
             {/* Map Background */}
             <img
               src="/world_map_tech.svg"
               alt="World Map"
               className="absolute inset-0 w-full h-full object-fill select-none pointer-events-none opacity-50"
               draggable={false}
             />

             {/* Grid Lines for Reference */}
             <div className="absolute inset-0 pointer-events-none opacity-20" 
                  style={{ 
                    backgroundImage: "linear-gradient(#444 1px, transparent 1px), linear-gradient(90deg, #444 1px, transparent 1px)",
                    backgroundSize: "5% 10%"
                  }} 
             />

             {/* Pins */}
             {cities.map((city) => (
               <div
                 key={city.id}
                 className={cn(
                   "absolute w-4 h-4 rounded-full border-2 cursor-grab active:cursor-grabbing transform -translate-x-1/2 -translate-y-1/2 flex items-center justify-center group",
                   selectedCityId === city.id ? "border-white z-50 scale-125" : "border-transparent z-10"
                 )}
                 style={{
                   left: `${city.coordinates.x}%`,
                   top: `${city.coordinates.y}%`,
                   backgroundColor: city.color,
                   boxShadow: selectedCityId === city.id ? "0 0 10px white" : "none"
                 }}
                 onMouseDown={(e) => handleMouseDown(e, city.id)}
               >
                 {/* Label on Hover/Select */}
                 <div className={cn(
                   "absolute -top-8 left-1/2 -translate-x-1/2 bg-black/80 text-white text-xs px-2 py-1 rounded whitespace-nowrap pointer-events-none transition-opacity",
                   selectedCityId === city.id ? "opacity-100" : "opacity-0 group-hover:opacity-100"
                 )}>
                   {city.name}
                 </div>
               </div>
             ))}
           </div>
        </div>
      </div>
    </div>
  )
}
